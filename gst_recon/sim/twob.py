"""Build GSTR-2B documents from what each supplier actually filed."""

from __future__ import annotations

import random
from collections import defaultdict
from datetime import date

from gst_recon.schema import (
    DocType,
    Gstr2b,
    Gstr2bB2bSupplier,
    Gstr2bCdnrSupplier,
    Gstr2bData,
    Gstr2bDocData,
    Gstr2bInvoice,
    Gstr2bItem,
    Gstr2bNote,
    Party,
    TruthLineItem,
)
from gst_recon.sim.money import r2, split_tax

GEN_DAY = 14  # GSTR-2B is generated on the 14th of the following month (r.60(7))


def _next_month(d: date, n: int = 1) -> date:
    y, m = divmod(d.month - 1 + n, 12)
    return date(d.year + y, m + 1, 1)


def _ddmmyyyy(d: date) -> str:
    return d.strftime("%d-%m-%Y")


def _items(lines: list[TruthLineItem]) -> list[Gstr2bItem]:
    by_rate: dict[float, list[TruthLineItem]] = defaultdict(list)
    for line in lines:
        by_rate[line.rate].append(line)
    return [
        Gstr2bItem(num=i, rt=rate, **{h: r2(sum(getattr(l, k) for l in ls))
                                      for h, k in (("txval", "taxable_value"), ("igst", "igst"),
                                                   ("cgst", "cgst"), ("sgst", "sgst"), ("cess", "cess"))})
        for i, (rate, ls) in enumerate(sorted(by_rate.items()), 1)
    ]


def _misreport(rng: random.Random, lines: list[TruthLineItem], intra: bool) -> list[TruthLineItem]:
    """Supplier reports a wrong taxable value on the first line (tax follows)."""
    src = lines[0]
    taxable = r2(src.taxable_value * rng.choice((0.5, 0.9, 1.1, 1.25)))
    igst, cgst, sgst = split_tax(taxable, src.rate, intra)
    cess = r2(src.cess * taxable / src.taxable_value) if src.taxable_value else 0.0
    return [src.model_copy(update=dict(taxable_value=taxable, igst=igst, cgst=cgst, sgst=sgst, cess=cess))] + lines[1:]


def build_gstr2b(rng: random.Random, drafts: list, buyer: Party, start: date, as_of: date) -> list[Gstr2b]:
    """2B for the case period, plus the next period's 2B if generated by as_of.
    Sets `draft.twob_key` for every document that appears in a provided 2B."""
    periods = [start, _next_month(start)]
    available = [p for p in periods if date(_next_month(p).year, _next_month(p).month, GEN_DAY) <= as_of or p == start]
    b2b: dict[date, dict[str, Gstr2bB2bSupplier]] = {p: {} for p in available}
    cdnr: dict[date, dict[str, Gstr2bCdnrSupplier]] = {p: {} for p in available}

    for d in drafts:
        inv, s = d.inv, d.supplier
        if d.twob in ("not_filed", "filed_wrong_buyer"):
            continue
        period = periods[1] if d.twob == "filed_late" else periods[0]
        if period not in available:
            continue
        intra = s.party.state_code == buyer.state_code
        lines = _misreport(rng, inv.line_items, intra) if d.twob == "filed_wrong_amount" else inv.line_items
        ctin = s.alt_gstin if d.twob == "filed_other_gstin" else inv.supplier_gstin
        supprd = period.strftime("%m%Y")
        filed = _ddmmyyyy(date(_next_month(period).year, _next_month(period).month, rng.randint(1, 11)))
        common = dict(dt=_ddmmyyyy(inv.invoice_date), val=inv.total, pos=inv.place_of_supply,
                      rev="Y" if inv.reverse_charge else "N", items=_items(lines))
        if inv.doc_type == DocType.CREDIT_NOTE:
            sup = cdnr[period].setdefault(ctin, Gstr2bCdnrSupplier(ctin=ctin, trdnm=s.party.name, supfildt=filed, supprd=supprd, nt=[]))
            sup.nt.append(Gstr2bNote(ntnum=inv.invoice_no, **common))
        else:
            sup = b2b[period].setdefault(ctin, Gstr2bB2bSupplier(ctin=ctin, trdnm=s.party.name, supfildt=filed, supprd=supprd, inv=[]))
            sup.inv.append(Gstr2bInvoice(inum=inv.invoice_no, **common))
        d.twob_key = (supprd, ctin, inv.invoice_no)

    return [
        Gstr2b(data=Gstr2bData(
            gstin=buyer.gstin, rtnprd=p.strftime("%m%Y"),
            gendt=_ddmmyyyy(date(_next_month(p).year, _next_month(p).month, GEN_DAY)),
            docdata=Gstr2bDocData(b2b=list(b2b[p].values()), cdnr=list(cdnr[p].values())),
        ))
        for p in available
    ]
