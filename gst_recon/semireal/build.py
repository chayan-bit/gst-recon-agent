from dataclasses import dataclass, field, replace
from datetime import date, timedelta
from pathlib import Path

from gst_recon.hybrid.docschema import DocRecord, to_truth_invoice
from gst_recon.hybrid.inputs import parse_date, parse_prompt
from gst_recon.render.prompt import assemble
from gst_recon.render.tables import render_bank, render_gstr2b, render_register
from gst_recon.render.tokens import count_tokens
from gst_recon.render.verify import Index, case_recall, check_doc, doc_facts
from gst_recon.schema import BuyerProfile, Case, CaseInputs, DocType, Party
from gst_recon.sim import catalog as cat
from gst_recon.sim.bank import build_bank_statement, plan_payments
from gst_recon.sim.gstin import is_valid_gstin, make_gstin
from gst_recon.sim.rules import Link, reconcile
from gst_recon.sim.suppliers import Supplier
from gst_recon.sim.twob import build_gstr2b
from gst_recon.sim.world import DIFFICULTY, PAY_ANOMALIES, REG_ANOMALIES, TWOB_ANOMALIES, Draft, _anomalies, _month_end, _register

VERSION = "semireal-1"
LEVELS = {"clean": replace(DIFFICULTY["medium"], p_side=0.0), "sim": DIFFICULTY["medium"]}
MAX_DOCS = 25
IDENTITY = ("supplier_gstin", "invoice_no", "invoice_date")
_PLANTED = set(TWOB_ANOMALIES + REG_ANOMALIES + PAY_ANOMALIES)


@dataclass(frozen=True)
class RealDoc:
    key: str  # caller's id for the document (never shown to the model)
    record: DocRecord  # labelled truth
    text: str  # document text, verbatim
    source: str  # section label, e.g. "scanned document, OCR text"
    confidence: str = ""
    absent: frozenset[str] = field(default_factory=frozenset)  # identity fields "" because the page prints none


def exclusion_reason(doc: RealDoc) -> str | None:
    """A document whose true identity is unknown cannot get books (the register and 2B would need the true
    value): an unreadable identity field, or a printed GSTIN that fails the check digit. A field the page does
    not print at all (an unregistered supplier's GSTIN) is known: it is "", and the books follow that."""
    r = doc.record
    unknown = [f for f in IDENTITY if not str(getattr(r, f)).strip() and f not in doc.absent]
    if unknown:
        return f"identity unknown: {', '.join(unknown)} unreadable in the label"
    g = r.supplier_gstin.strip()
    if g and not is_valid_gstin(g):  # a registration that fails the check digit cannot be in GSTR-2B; the true one is unknown
        return "identity unknown: supplier_gstin fails the mod-36 check digit (true registration unknown)"
    try:
        parse_date(r.invoice_date)
    except (ValueError, KeyError):
        return f"identity unknown: invoice_date {r.invoice_date!r} unparseable"
    return None


def group_docs(docs: list[RealDoc], max_docs: int = MAX_DOCS) -> list[tuple[str, list[RealDoc]]]:
    """(key, docs): one buyer-month per case, a month above max_docs split into near-equal chunks.
    key = YYYYMM, with -1, -2, ... when split. Callers pass only documents without an exclusion reason."""
    months: dict[str, list[RealDoc]] = defaultdict(list)
    for d in sorted(docs, key=lambda d: d.key):
        months[parse_date(d.record.invoice_date).strftime("%Y%m")].append(d)
    out = []
    for ym, ds in sorted(months.items()):
        k = math.ceil(len(ds) / max_docs)
        size = math.ceil(len(ds) / k)
        chunks = [ds[i:i + size] for i in range(0, len(ds), size)]
        out += [(ym if k == 1 else f"{ym}-{i}", c) for i, c in enumerate(chunks, 1)]
    return out


def _supplier(rng: random.Random, rec: DocRecord, buyer: Party) -> Supplier:
    g = rec.supplier_gstin.strip().upper()
    state = g[:2] if g[:2].isdigit() else rec.place_of_supply or buyer.state_code
    other = rng.choice([s for s in sorted(cat.STATES) if s != state])
    alt = make_gstin(other, g[2:12]) if len(g) == 15 else ""  # same PAN, another state (2B filed_other_gstin)
    return Supplier(Party(name=rec.supplier_name, gstin=g, state_code=state, address=""), alt, (), "real", "", 0)


def _drafts(rng: random.Random, docs: list[RealDoc], buyer: Party, level: str, late: bool) -> tuple[list[Draft], list[str]]:
    """Drafts in doc_id order with the simulator's per-document anomaly draws; returns (drafts, structural notes)."""
    suppliers: dict[str, Supplier] = {}
    drafts, notes = [], []
    for i, d in enumerate(docs, 1):
        rec, doc_id = d.record, f"D{i:02d}"
        inv = to_truth_invoice(doc_id, rec, buyer_gstin=buyer.gstin, buyer_name=buyer.name, when=parse_date(rec.invoice_date))
        s = suppliers.setdefault(inv.supplier_gstin or f"name:{inv.supplier_name}", _supplier(rng, rec, buyer))
        dr = Draft(inv, s, "real", **_anomalies(rng, LEVELS[level], late, inv.doc_type == DocType.INVOICE))
        if not inv.supplier_gstin:  # unregistered supplier: never in any GSTR-2B, no GSTIN to mistype
            notes.append(f"{doc_id}:unregistered_supplier_not_in_2b")
            dr.twob = "not_filed"
            dr.reg = None if dr.reg == "reg_gstin_typo" else dr.reg
        drafts.append(dr)
    for dr in drafts:  # credit notes reduce the payment of their original when it is in the same case
        if dr.inv.doc_type == DocType.CREDIT_NOTE:
            dr.credit_note_of = next((o for o in drafts if o.inv.doc_type == DocType.INVOICE and o.supplier is dr.supplier
                                      and o.inv.invoice_no == dr.inv.original_invoice_no), None)
            if dr.credit_note_of:
                notes.append(f"{dr.inv.doc_id}:credit_note_of:{dr.credit_note_of.inv.doc_id}")
    return drafts, notes


def build_case(key: str, docs: list[RealDoc], buyer: Party, profile: BuyerProfile, level: str, seed: int = 0) -> tuple[Case, list[RealDoc]]:
    """One case from one group. The document order and reconciliation date use an rng that does not depend on
    the level, so `clean` and `sim` share them. Returns (truth Case, docs in D01.. order)."""
    rng = random.Random(f"semireal:{seed}:{key}")
    docs = sorted(docs, key=lambda d: d.key)
    rng.shuffle(docs)  # document position carries no information
    y, m = int(key[:4]), int(key[4:6])
    start, end = date(y, m, 1), _month_end(y, m)
    late = rng.random() < LEVELS["sim"].p_late_recon
    as_of = end + timedelta(days=rng.randint(190, 230) if late else rng.randint(12, 25))
    rng = random.Random(f"semireal:{seed}:{key}:{level}")
    drafts, notes = _drafts(rng, docs, buyer, level, late)
    register = _register(rng, drafts, end)
    gstr2b = build_gstr2b(rng, drafts, buyer, start, as_of)
    bank = build_bank_statement(rng, plan_payments(rng, drafts, as_of), start, as_of)
    inputs = CaseInputs(buyer=buyer, buyer_profile=profile, period=f"{m:02d}{y}", as_of_date=as_of,
                        invoices=[d.inv for d in drafts], purchase_register=register, gstr2b=gstr2b, bank_statement=bank)
    links = {d.inv.doc_id: Link(tuple(d.vouchers), d.twob_key, tuple(d.payment_refs)) for d in drafts}
    structural = {n.split(":", 1)[0] for n in notes if "unregistered" in n}
    planted = [f"{d.inv.doc_id}:{a}" for d in drafts for a in (d.twob, d.reg, d.pay)
               if a and not (a == "not_filed" and d.inv.doc_id in structural)]
    case = Case(case_id=f"semireal-{level}-{key}", seed=seed, difficulty=level, split=f"semireal_{level}", inputs=inputs,
                expected=reconcile(inputs, links), anomalies=planted + notes + (["late_reconciliation"] if late else []))
    return case, docs


def _check_round_trip(prompt: str, case: Case, blocks: list[tuple[str, str, str]]) -> None:
    """The hybrid parsers must read back exactly what was written (a document text that looks like a section
    marker would break the case)."""
    p = parse_prompt(prompt)
    got = [(d.doc_id, d.source, d.text) for d in p.docs]
    if got != blocks or p.register != case.inputs.purchase_register or p.gstr2b != case.inputs.gstr2b:
        raise ValueError(f"{case.case_id}: prompt does not parse back to its parts")
    if (p.header.profile, p.header.period, p.header.as_of) != (case.inputs.buyer_profile, case.inputs.period, case.inputs.as_of_date):
        raise ValueError(f"{case.case_id}: header does not parse back")


def write_case(case: Case, docs: list[RealDoc], out: Path, truth_out: Path) -> dict:
    """<out>/<case_id>/{prompt.txt,target.json,meta.json} (the eval case format) + <truth_out>/<case_id>.json."""
    cid, inp = case.case_id, case.inputs
    blocks = [(inv.doc_id, d.source, d.text.rstrip("\n")) for inv, d in zip(inp.invoices, docs)]
    reg_text, reg_meta = render_register(inp.purchase_register, inp.period, inp.buyer.name, random.Random(f"{cid}:register"))
    bank_text, bank_meta = render_bank(inp.bank_statement, random.Random(f"{cid}:bank"))
    prompt, rest = assemble(case, blocks, (f"Tally {reg_meta['style']} export", reg_text), render_gstr2b(inp.gstr2b),
                            (f"{bank_meta['bank_style'].upper()} CSV", bank_text))
    _check_round_trip(prompt, case, blocks)
    rest_ix = Index.of(rest)
    recalls = [check_doc(inv.doc_id, doc_facts(inv, inv.invoice_date.isoformat()), t, rest_ix) for inv, (_, _, t) in zip(inp.invoices, blocks)]
    target = case.expected.model_dump_json(indent=None)
    p_tok, method = count_tokens(prompt)
    t_tok, _ = count_tokens(target)
    meta = {"case_id": cid, "seed": case.seed, "difficulty": case.difficulty, "split": case.split, "render_version": VERSION,
            "eval_only": True, "documents": [{"doc_id": inv.doc_id, "source_key": d.key, "source": d.source, "confidence": d.confidence,
                                              "doc_type": inv.doc_type.value} for inv, d in zip(inp.invoices, docs)],
            "anomalies": case.anomalies, "register": reg_meta, "bank": bank_meta, "prompt_chars": len(prompt),
            "prompt_tokens": p_tok, "target_tokens": t_tok, "token_method": method,
            **case_recall(recalls, {inv.doc_id for inv in inp.invoices})}
    final, tmp = out / cid, out / f".{cid}.tmp"
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    for name, text in (("prompt.txt", prompt), ("target.json", target), ("meta.json", json.dumps(meta, indent=1))):
        (tmp / name).write_text(text, encoding="utf-8")
    shutil.rmtree(final, ignore_errors=True)
    tmp.rename(final)
    truth_out.mkdir(parents=True, exist_ok=True)
    (truth_out / f"{cid}.json").write_text(case.model_dump_json(indent=1))
    return meta


def build_set(docs: list[RealDoc], buyer: Party, profile: BuyerProfile, out: Path, *, seed: int = 0,
              max_docs: int = MAX_DOCS, levels: tuple[str, ...] = tuple(LEVELS)) -> dict:
    """Write <out>/<level>/<case_id>/... and <out>/truth/<level>/<case_id>.json; returns the manifest."""
    excluded = [{"source_key": d.key, "reason": r} for d in docs if (r := exclusion_reason(d))]
    kept = [d for d in docs if not exclusion_reason(d)]
    manifest: dict = {"version": VERSION, "eval_only": True, "seed": seed, "max_docs": max_docs, "excluded": excluded,
                      "n_input_docs": len(docs), "n_kept_docs": len(kept), "levels": {}}
    groups = group_docs(kept, max_docs)
    for level in levels:
        rows = []
        for key, group in groups:
            case, ordered = build_case(key, group, buyer, profile, level, seed)
            meta = write_case(case, ordered, out / level, out / "truth" / level)
            rows.append({"case_id": case.case_id, "period": case.inputs.period, "as_of": case.inputs.as_of_date.isoformat(),
                         "docs": meta["documents"], "anomalies": case.anomalies,
                         "planted": [a for a in case.anomalies if a.split(":")[-1] in _PLANTED],
                         "prompt_tokens": meta["prompt_tokens"], "ocr_recall": meta["ocr_recall"]})
        manifest["levels"][level] = {"n_cases": len(rows), "n_docs": sum(len(r["docs"]) for r in rows), "cases": rows}
    return manifest

