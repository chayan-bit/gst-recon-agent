"""Real documents + simulated books: labelled real purchase documents become the documents of full eval cases.

The documents (their text verbatim, and their labelled DocRecord as truth) are real; the purchase register,
GSTR-2B and bank statement around them are generated by the simulator's own functions (`sim.world._register`,
`sim.twob.build_gstr2b`, `sim.bank.plan_payments` / `build_bank_statement`) with the simulator's anomaly draws,
and the target comes from `sim.rules.reconcile`, the same code path as every simulated case. EVAL ONLY.

Noise levels: `clean` (no planted book discrepancies; payments still exist) and `sim` (the simulator's default
per-document anomaly rate, `sim.world.DIFFICULTY["medium"]`, the generator CLI's default).
"""

from __future__ import annotations

import json
import math
import random
import shutil
